import type { Job } from "bullmq";
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import { prisma } from "../src/lib/prisma.js";
import { closeQueues } from "../src/lib/queue.js";
import { redis } from "../src/lib/redis.js";
import { ensureBucket } from "../src/lib/storage.js";
import { generateTicketPdf } from "../src/modules/tickets/tickets.jobs.js";
import type { TicketPdfJobData } from "../src/modules/tickets/tickets.service.js";
import {
  api,
  bearer,
  book,
  buyer,
  makeAdmin,
  makeOrganizer,
  publishedEvent,
  resetState,
} from "./helpers.js";

beforeAll(ensureBucket);
beforeEach(resetState);
afterAll(async () => {
  await closeQueues();
  await prisma.$disconnect();
  await redis.quit();
});

const renderPdf = (ticketId: string) =>
  generateTicketPdf({ data: { ticketId } } as Job<TicketPdfJobData>);

/** Organizer + free published event + a buyer holding `quantity` tickets. */
async function setup(quantity = 2) {
  const org = await makeOrganizer();
  const { eventId, ticketTypeId } = await publishedEvent(org.token, { price: 0 });
  const b = await buyer();
  const res = await book(b.token, { eventId, items: [{ ticketTypeId, quantity }] });
  expect(res.body.booking.status).toBe("confirmed");
  const tickets = res.body.booking.tickets as { id: string; ticketCode: string }[];
  return { org, b, eventId, ticketTypeId, tickets };
}

describe("my tickets", () => {
  it("lists my tickets and shows one with its QR and the online link", async () => {
    const { b, tickets } = await setup(2);
    const list = await api().get("/api/v1/me/tickets").set(bearer(b.token));
    expect(list.status).toBe(200);
    expect(list.body.data).toHaveLength(2);
    expect(list.body.data[0]).toMatchObject({
      status: "valid",
      ticketType: { name: "General" },
      event: { title: "Test Gig", mode: "online" },
      pdfReady: false,
    });
    expect(
      (await api().get("/api/v1/me/tickets?upcoming=true").set(bearer(b.token))).body.data,
    ).toHaveLength(2);

    const one = await api().get(`/api/v1/tickets/${tickets[0]!.id}`).set(bearer(b.token));
    expect(one.status).toBe(200);
    expect(one.headers["cache-control"]).toBe("private, no-store");
    expect(one.body.ticket.qr.payload).toBe(tickets[0]!.ticketCode);
    expect(one.body.ticket.qr.svg).toMatch(/^<svg/);
    // hidden on the public event page, revealed to ticket holders
    expect(one.body.ticket.event.onlineUrl).toBe("https://meet.example.com/gig");
  });

  it("other people can't see my ticket", async () => {
    const { tickets } = await setup(1);
    const stranger = await buyer("stranger@example.com");
    expect(
      (await api().get(`/api/v1/tickets/${tickets[0]!.id}`).set(bearer(stranger.token))).status,
    ).toBe(404);
    expect(
      (await api().get(`/api/v1/tickets/${tickets[0]!.id}/pdf`).set(bearer(stranger.token))).status,
    ).toBe(404);
  });
});

describe("ticket PDF", () => {
  it("is generated by the worker and downloaded through a short-lived signed link", async () => {
    const { b, tickets } = await setup(1);
    const id = tickets[0]!.id;

    const early = await api().get(`/api/v1/tickets/${id}/pdf`).set(bearer(b.token));
    expect(early.status).toBe(409);
    expect(early.body.code).toBe("PDF_NOT_READY");

    await renderPdf(id);
    const row = await prisma.ticket.findUniqueOrThrow({ where: { id } });
    expect(row.pdfKey).toMatch(new RegExp(`^tickets/.+/${id}-\\d+\\.pdf$`));

    const res = await api().get(`/api/v1/tickets/${id}/pdf`).set(bearer(b.token));
    expect(res.status).toBe(302);
    expect(res.headers.location).toMatch(/X-Amz-Signature=/);
    const file = await fetch(res.headers.location!);
    expect(file.status).toBe(200);
    expect(file.headers.get("content-type")).toBe("application/pdf");
    expect(file.headers.get("content-disposition")).toMatch(/attachment; filename=".+\.pdf"/);
    const bytes = Buffer.from(await file.arrayBuffer());
    expect(bytes.subarray(0, 5).toString()).toBe("%PDF-");

    // the object itself is private: without the signature → 403
    const unsigned = res.headers.location!.split("?")[0]!;
    expect((await fetch(unsigned)).status).toBe(403);

    const json = await api().get(`/api/v1/tickets/${id}/pdf?redirect=false`).set(bearer(b.token));
    expect(json.body).toMatchObject({ expiresInSeconds: 300 });
    expect(json.body.url).toMatch(/^http/);
  });

  it("assigning a guest re-renders the PDF; a stale render is discarded", async () => {
    const { b, tickets } = await setup(1);
    const id = tickets[0]!.id;
    await renderPdf(id);

    const res = await api()
      .patch(`/api/v1/tickets/${id}/holder`)
      .set(bearer(b.token))
      .send({ holderName: "Sita Sharma", holderEmail: "Sita@Example.com" });
    expect(res.status).toBe(200);
    expect(res.body.ticket).toMatchObject({
      holderName: "Sita Sharma",
      holderEmail: "sita@example.com",
      pdfReady: false,
    });

    await renderPdf(id);
    expect((await prisma.ticket.findUniqueOrThrow({ where: { id } })).pdfKey).not.toBeNull();

    // bad input
    expect(
      (
        await api()
          .patch(`/api/v1/tickets/${id}/holder`)
          .set(bearer(b.token))
          .send({ holderName: "" })
      ).status,
    ).toBe(400);
  });
});

describe("check-in", () => {
  const scan = (token: string, eventId: string, ticketCode: string) =>
    api().post(`/api/v1/events/${eventId}/check-ins`).set(bearer(token)).send({ ticketCode });

  it("admits a valid ticket once; the second scan says when and by whom", async () => {
    const { org, b, eventId, tickets } = await setup(2);
    const code = tickets[0]!.ticketCode;

    const first = await scan(org.token, eventId, code.toLowerCase()); // forgiving about case
    expect(first.status).toBe(200);
    expect(first.body).toMatchObject({
      result: "admitted",
      ticket: { ticketCode: code, ticketType: "General", holderName: "Alice Test" },
    });

    const second = await scan(org.token, eventId, code);
    expect(second.status).toBe(409);
    expect(second.body.code).toBe("ALREADY_CHECKED_IN");
    expect(second.body.details).toMatchObject({ checkedInBy: "Alice Test" });
    expect(second.body.details.checkedInAt).toBeTruthy();

    // a checked-in ticket can't be handed to someone else
    const reassign = await api()
      .patch(`/api/v1/tickets/${tickets[0]!.id}/holder`)
      .set(bearer(b.token))
      .send({ holderName: "Someone Else" });
    expect(reassign.body.code).toBe("TICKET_NOT_TRANSFERABLE");
  });

  it("two gates scanning the same QR at once: exactly one admits", async () => {
    const { org, eventId, tickets } = await setup(1);
    const results = await Promise.all(
      Array.from({ length: 8 }, () => scan(org.token, eventId, tickets[0]!.ticketCode)),
    );
    expect(results.filter((r) => r.status === 200)).toHaveLength(1);
    expect(results.filter((r) => r.body.code === "ALREADY_CHECKED_IN")).toHaveLength(7);
  });

  it("rejects unknown codes, other events' tickets and malformed input", async () => {
    const { org, eventId, tickets } = await setup(1);
    const other = await publishedEvent(org.token, { title: "Other Gig", price: 0 });

    expect((await scan(org.token, eventId, "TKT-0000000000000000")).body.code).toBe(
      "TICKET_NOT_FOUND",
    );
    expect((await scan(org.token, other.eventId, tickets[0]!.ticketCode)).body.code).toBe(
      "WRONG_EVENT",
    );
    expect((await scan(org.token, eventId, "not-a-code")).status).toBe(400);

    await prisma.ticket.update({ where: { id: tickets[0]!.id }, data: { status: "cancelled" } });
    expect((await scan(org.token, eventId, tickets[0]!.ticketCode)).body.code).toBe(
      "TICKET_NOT_VALID",
    );
  });

  it("only the organizer, admins and event staff can scan; closed after cancellation", async () => {
    const { org, eventId, tickets } = await setup(2);
    const scanner = await buyer("scanner@example.com");
    const admin = await makeAdmin();

    expect((await scan(scanner.token, eventId, tickets[0]!.ticketCode)).status).toBe(404);

    // organizer adds a scanner by email
    const add = await api()
      .post(`/api/v1/events/${eventId}/staff`)
      .set(bearer(org.token))
      .send({ email: "SCANNER@example.com" });
    expect(add.status).toBe(201);
    expect(add.body.staff).toMatchObject({ email: "scanner@example.com", role: "scanner" });
    expect(
      (await api().get(`/api/v1/events/${eventId}/staff`).set(bearer(org.token))).body.data,
    ).toHaveLength(1);
    // staff can't manage staff
    expect(
      (await api().get(`/api/v1/events/${eventId}/staff`).set(bearer(scanner.token))).status,
    ).toBe(404);
    expect(
      (
        await api()
          .post(`/api/v1/events/${eventId}/staff`)
          .set(bearer(org.token))
          .send({ email: "nobody@example.com" })
      ).body.code,
    ).toBe("USER_NOT_FOUND");

    const mine = await api().get("/api/v1/me/staff-events").set(bearer(scanner.token));
    expect(mine.body.data).toMatchObject([{ eventId, role: "scanner", title: "Test Gig" }]);

    expect((await scan(scanner.token, eventId, tickets[0]!.ticketCode)).body.result).toBe(
      "admitted",
    );
    expect((await scan(admin, eventId, tickets[1]!.ticketCode)).body.result).toBe("admitted");

    // removed staff lose access
    expect(
      (await api().delete(`/api/v1/events/${eventId}/staff/${scanner.id}`).set(bearer(org.token)))
        .status,
    ).toBe(204);
    expect((await scan(scanner.token, eventId, tickets[0]!.ticketCode)).status).toBe(404);

    await api()
      .post(`/api/v1/events/${eventId}/cancel`)
      .set(bearer(org.token))
      .send({ reason: "Storm" });
    expect((await scan(org.token, eventId, tickets[0]!.ticketCode)).body.code).toBe(
      "EVENT_NOT_ACTIVE",
    );
  });

  it("stats show issued vs checked in", async () => {
    const { org, eventId, tickets } = await setup(3);
    await scan(org.token, eventId, tickets[0]!.ticketCode);
    const res = await api().get(`/api/v1/events/${eventId}/check-ins/stats`).set(bearer(org.token));
    expect(res.status).toBe(200);
    expect(res.body).toMatchObject({ issued: 3, checkedIn: 1, remaining: 2 });
    expect(res.body.byTicketType).toMatchObject([{ name: "General", issued: 3, checkedIn: 1 }]);
  });
});
